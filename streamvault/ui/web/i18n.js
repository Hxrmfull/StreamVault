  function t(text, params) {
    let result = language === "en" && Object.prototype.hasOwnProperty.call(EN, text) ? EN[text] : text;
    if (params) {
      result = result.replace(/\{(\w+)\}/g, (whole, name) =>
        Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : whole);
    }
    return result;
  }

  // слово для числа; forms — русские формы через "|": "файл|файла|файлов"
  function tp(count, forms) {
    if (language === "en") {
      const english = (EN[forms] || forms).split("|");
      return Math.abs(count) === 1 ? english[0] : english[english.length - 1];
    }
    const [one, few, many] = forms.split("|");
    const n = Math.abs(Math.floor(count)) % 100;
    if (n > 10 && n < 20) return many;
    const last = n % 10;
    if (last === 1) return one;
    if (last > 1 && last < 5) return few;
    return many;
  }

